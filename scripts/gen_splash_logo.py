#!/usr/bin/env python3
"""Generate the shared first-splash RGB565 bitmap from its lossless master.

    python3 scripts/gen_splash_logo.py
    python3 scripts/gen_splash_logo.py --check

Requires Pillow, like gen_splash_small.py. Only seeder_logo and the matching
legacy BLACK_small bitmap are generated; the credit artwork is not touched.
"""
import argparse
import pathlib
import re

try:
    from PIL import Image
except ImportError:
    raise SystemExit("Pillow is required: python3 -m pip install pillow")


ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Logo" / "seeder-splash.png"
WIDTH, HEIGHT = 200, 88
COUNT = WIDTH * HEIGHT


def pixels():
    with Image.open(SOURCE) as image:
        if image.size != (WIDTH, HEIGHT) or image.mode != "RGB":
            raise ValueError("seeder-splash.png must be a 200x88 RGB image")
        raw = image.tobytes()
    return [((raw[i] >> 3) << 11) | ((raw[i + 1] >> 2) << 5)
            | (raw[i + 2] >> 3) for i in range(0, len(raw), 3)]


def body(values):
    # Match the original ImageConverter formatting so unchanged pixels do not
    # produce a wholesale diff of this otherwise large generated array.
    lines = []
    for start in range(0, len(values), 16):
        row = values[start:start + 16]
        end = start + len(row)
        lines.append(", ".join("0x%04X" % value for value in row)
                     + ",   // 0x%04X (%d)" % (end, end))
    return "\n" + "\n".join(lines) + "\n"


def replace_bitmap(text, name, generated):
    pattern = re.compile(r"(\b" + re.escape(name)
                         + r"\s*\[0x44C0\]\s*PROGMEM\s*=\s*\{)(.*?)(\};)",
                         re.DOTALL)
    matches = list(pattern.finditer(text))
    if len(matches) != 1:
        raise ValueError("expected one 200x88 %s bitmap" % name)
    match = matches[0]
    return text[:match.start(2)] + generated + text[match.end(2):]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="report stale generated assets without writing")
    args = parser.parse_args()
    values = pixels()
    if len(values) != COUNT:
        raise ValueError("expected %d RGB565 pixels" % COUNT)
    generated = body(values)

    changed = []
    for relative, name in (("src/Lib/images.h", "seeder_logo"),
                           ("Logo/BLACK_small.c", "BLACK_small")):
        path = ROOT / relative
        before = path.read_text(encoding="utf-8")
        after = replace_bitmap(before, name, generated)
        if name == "seeder_logo":
            note = ("// Generated from Logo/seeder-splash.png by "
                    "scripts/gen_splash_logo.py.\n")
            declaration = "const unsigned short seeder_logo"
            if note not in after:
                after = after.replace(declaration, note + declaration, 1)
        else:
            metadata = re.compile(
                r"^// Generated by[^\n]*\n// Generated from[^\n]*\n"
                r"// (?:Time generated|Original artwork)[^\n]*\n", re.MULTILINE)
            note = ("// Generated by  : scripts/gen_splash_logo.py\n"
                    "// Generated from: seeder-splash.png\n"
                    "// Original artwork: BLACK_small.jpg / ImageConverter 565 v2.1 (2022)\n")
            after, count = metadata.subn(note, after, count=1)
            if count != 1:
                raise ValueError("expected BLACK_small.c provenance header")
        if before != after:
            changed.append(relative)
            if not args.check:
                path.write_text(after, encoding="utf-8", newline="\n")

    if args.check and changed:
        parser.exit(1, "stale splash assets: " + ", ".join(changed) + "\n")
    print("updated: " + ", ".join(changed)
          if changed else "all splash assets are current")


if __name__ == "__main__":
    main()
